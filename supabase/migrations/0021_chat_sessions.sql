-- Transcripts of the website contact chat (src/components/contact-chat.tsx). The chat saves its conversation
-- as it goes through a Server Action with the service-role key, so there is no public insert policy; only
-- staff can read or delete them. A session is kept from the visitor's first message onwards and linked to the
-- lead once the enquiry is submitted. `messages` is [{ from: 'bot' | 'you', text, at }], in order.

create table public.chat_sessions (
  id          uuid primary key,                 -- generated by the browser so the transcript can be updated as it grows
  page        text,                             -- where on the site the chat was opened
  name        text,                             -- filled in once the visitor gives them
  phone       text,
  messages    jsonb not null default '[]'::jsonb,
  lead_id     uuid references public.leads (id) on delete set null,
  started_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index chat_sessions_started_idx on public.chat_sessions (started_at desc);

alter table public.chat_sessions enable row level security;

create policy "staff read chat sessions" on public.chat_sessions for select to authenticated using ((select public.is_staff()));
create policy "staff delete chat sessions" on public.chat_sessions for delete to authenticated using ((select public.is_staff()));
